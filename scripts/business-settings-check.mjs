import { _electron as electron } from 'playwright'
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import assert from 'node:assert/strict'
import * as core from '../src/core/index.js'
const out=resolve('docs/verification/iv-businesses');mkdirSync(out,{recursive:true})
const data=mkdtempSync(join(tmpdir(),'iv-business-ui-'))
const db=core.openDb(join(data,'fitscout.db'))
const a=core.createBusiness(db,{name:'Fictional North Studio',profile:{offer:'Booking websites'}})
db.prepare('update businesses set profile_json=? where id=?').run(JSON.stringify({...a.profile,name:''}),a.id) // Legacy onboarding stored the person's name separately.
const campaign=core.createCampaign(db,{name:'Local referral partners',business_id:a.id})
core.addLeads(db,campaign.id,[{company:'Fictional Cedar Dental',website:'cedar.example.test'}]);db.close()
const packaged=process.argv.includes('--packaged')
const launch=()=>electron.launch({...packaged?{executablePath:resolve('dist/win-unpacked/IV Outreach.exe')}:{args:['.'],cwd:process.cwd()},env:{...process.env,FITSCOUT_DATA_DIR:data}})
let app=await launch(),win=await app.firstWindow();const errors=[]
const prepare=async()=>{win.setDefaultTimeout(15000);win.on('pageerror',e=>errors.push(String(e)));await win.setViewportSize({width:1360,height:880});await win.emulateMedia({reducedMotion:'reduce'})}
await prepare()
try {
  await win.locator('#business-picker').selectOption(a.id)
  await win.click('.nav button:has-text("Leads")')
  await win.locator('main').getByText('Fictional Cedar Dental',{exact:true}).waitFor()
  await win.getByRole('button',{name:'Add a business',exact:true}).click()
  const dialog=win.getByRole('dialog',{name:'Add a business',exact:true})
  await dialog.getByLabel('Business name',{exact:true}).fill('Fictional South Realty')
  await dialog.getByLabel('What do you offer? (optional)',{exact:true}).fill('Real estate guidance')
  await dialog.getByRole('button',{name:'Add business',exact:true}).click()
  await dialog.waitFor({state:'hidden'})
  await win.waitForFunction(()=>document.querySelector('#business-picker').selectedOptions[0].text==='Fictional South Realty')
  assert.equal(await win.locator('main').getByText('Fictional Cedar Dental',{exact:true}).count(),0)
  assert.equal(await win.locator('#campaign-picker').isDisabled(),true)
  const b=await win.locator('#business-picker').inputValue()
  await win.getByRole('button',{name:'Add a campaign',exact:true}).click()
  const create=win.getByRole('dialog',{name:'Create a campaign',exact:true})
  assert.equal(await create.getByLabel('What do you offer? (optional)',{exact:true}).inputValue(),'Real estate guidance')
  await create.getByLabel('Campaign name',{exact:true}).fill('New homeowner referrals')
  await create.getByRole('button',{name:'Create campaign',exact:true}).click()
  await create.waitFor({state:'hidden'})
  await win.waitForFunction(()=>document.querySelector('#campaign-picker').selectedOptions[0].text==='New homeowner referrals')
  const c=await win.locator('#campaign-picker').inputValue()
  await win.click('.nav button:has-text("Settings")')
  await win.locator('#setup-businesses input[aria-label="Business name"]').waitFor()
  await win.screenshot({path:join(out,'settings-businesses.png')})
  await win.getByLabel('Brand voice',{exact:true}).fill('Warm, helpful, concise')
  const topics=win.getByRole('navigation',{name:'Settings sections'})
  await topics.getByRole('button',{name:/Mailbox/}).click()
  assert.equal(await topics.getByRole('button',{name:/Mailbox/}).getAttribute('aria-current'),'location')
  await win.screenshot({path:join(out,'settings-mailbox.png')})
  await topics.getByRole('button',{name:/Businesses/}).click()
  assert.equal(await win.getByLabel('Brand voice',{exact:true}).inputValue(),'Warm, helpful, concise')
  await win.getByRole('button',{name:'Save business profile',exact:true}).click()
  await win.getByText('Business profile saved.',{exact:true}).waitFor()
  await win.locator('#business-picker').selectOption(a.id)
  await win.waitForFunction(()=>document.querySelector('#setup-businesses input[aria-label="Business name"]').value==='Fictional North Studio')
  const row=win.locator('.business-campaign-row').filter({hasText:'Local referral partners'})
  await row.getByRole('button',{name:'Edit campaign',exact:true}).click()
  await row.getByLabel('Belongs to business').selectOption(b)
  await row.getByRole('button',{name:'Move campaign & history',exact:true}).click()
  await row.waitFor({state:'hidden'})
  await win.locator('#business-picker').selectOption(b)
  await win.locator('#campaign-picker').selectOption(campaign.id)
  await win.click('.nav button:has-text("Leads")')
  await win.locator('main').getByText('Fictional Cedar Dental',{exact:true}).waitFor()
  const chatState=await win.evaluate(()=>window.fitscout.call('chatWindowState'))
  assert.equal(chatState.context.businessId,b); assert.equal(chatState.context.campaignId,campaign.id)
  await win.screenshot({path:join(out,'business-campaign-picker.png')})
  await win.locator('#campaign-picker').selectOption(c)
  await win.waitForFunction(async()=>{const s=await window.fitscout.call('workspaceState');return s.campaignId===document.querySelector('#campaign-picker').value})
  await app.close();app=await launch();win=await app.firstWindow();await prepare()
  await win.waitForFunction(({b,c})=>document.querySelector('#business-picker')?.value===b && document.querySelector('#campaign-picker')?.value===c,{b,c})
  const work=await win.evaluate(()=>window.fitscout.call('workspaceState'))
  assert.equal(work.businesses.find(x=>x.id===b).profile.voice,'Warm, helpful, concise')
  await win.click('.nav button:has-text("Settings")')
  await win.locator('#setup-businesses').waitFor()
  for (const topic of ['Research','Premium & credits','Sender profile','Mailbox','Other apps','Do not contact']) {
    await win.getByRole('navigation',{name:'Settings sections'}).getByRole('button',{name:new RegExp(topic)}).click()
    assert.equal(await win.locator('main').evaluate(el=>el.scrollWidth>el.clientWidth+2),false,`${topic} overflows main`)
  }
  assert.deepEqual(errors,[])
  writeFileSync(join(out,'ui-result.json'),JSON.stringify({passed:true,packaged,data,checks:['business creation','campaign creation and inherited offer','empty business isolation','settings navigation retains unsaved fields','business profile saves','campaign move retains leads','chat context follows selection','workspace selection survives restart','no horizontal page overflow','no renderer errors']},null,2))
  console.log('Business / campaign / Settings UI checks passed.')
}finally{await app.close()}
